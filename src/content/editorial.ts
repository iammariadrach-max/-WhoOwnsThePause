export type EditorialBlock =
  | { type: "heading"; text: string; level: 2 | 3 }
  | { type: "source"; numbers: string }
  | {
      type:
        | "paragraph"
        | "lead"
        | "body-large"
        | "instruction"
        | "status"
        | "quote"
        | "caption"
        | "display";
      text: string;
    }
  | { type: "list"; ordered?: boolean; items: readonly string[] };

const p = (text: string): EditorialBlock => ({ type: "paragraph", text });
